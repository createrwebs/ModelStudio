def translate_phrase_deep(text: str, zh_text: str = '') -> str:
    # 1. Exact match in master dictionary
    if text in DICTIONARY:
        return DICTIONARY[text]
    if zh_text in DICTIONARY:
        return DICTIONARY[zh_text]

    # 2. Chinese substring & template replacement
    if zh_text:
        z = zh_text.strip()
        # Direct word replacements for compound Chinese
        for zh_word, th_word in DICTIONARY.items():
            if zh_word == z:
                return th_word

    return text

def run():
    total_translated = 0
    th_files = sorted(glob.glob(os.path.join(TH_DIR, '*.json')))
    for th_file in th_files:
        fname = os.path.basename(th_file)
        zh_file = os.path.join(ZH_DIR, fname)
        en_file = os.path.join(EN_DIR, fname)

        with open(th_file, 'r', encoding='utf-8') as f:
            th_data = json.load(f)

        zh_data = {}
        if os.path.exists(zh_file):
            with open(zh_file, 'r', encoding='utf-8') as f:
                zh_data = json.load(f)

        en_data = {}
        if os.path.exists(en_file):
            with open(en_file, 'r', encoding='utf-8') as f:
                en_data = json.load(f)

        count = 0
        for k, v in th_data.items():
            if isinstance(v, dict):
                msg = v.get('message', '')
                if not has_thai(msg) and re.search(r'[a-zA-Z\u4E00-\u9FFF]', msg):
                    z_val = zh_data.get(k, {})
                    z_msg = z_val.get('message', '') if isinstance(z_val, dict) else str(z_val)
                    new_msg = translate_phrase_deep(msg, z_msg)
                    if new_msg != msg and has_thai(new_msg):
                        v['message'] = new_msg
                        count += 1
            elif isinstance(v, str):
                if not has_thai(v) and re.search(r'[a-zA-Z\u4E00-\u9FFF]', v):
                    z_val = zh_data.get(k, '')
                    z_msg = z_val.get('message', '') if isinstance(z_val, dict) else str(z_val)
                    new_msg = translate_phrase_deep(v, z_msg)
                    if new_msg != v and has_thai(new_msg):
                        th_data[k] = new_msg
                        count += 1

        if count > 0:
            with open(th_file, 'w', encoding='utf-8') as f:
                json.dump(th_data, f, ensure_ascii=False, indent=2)
            print(f"[{fname}] Translated {count} keys")
            total_translated += count

    print(f"\nCompleted! Translated {total_translated} additional keys.")

if __name__ == '__main__':
    run()
